def port_is_open(host: str, port: int, timeout: float = 0.3) -> bool:
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def wait_for_port(host: str, port: int, timeout: float = 20.0) -> bool:
    deadline = time.time() + timeout
    while time.time() < deadline:
        if port_is_open(host, port):
            return True
        time.sleep(0.2)
    return False


class PluginProcess:
    """启停 DPI 插件，并保证**无论如何都把 DPI 复位**。

    停止顺序：优雅信号（让插件自己走 ``finally: stop(restore=True)``）→
    兜底强杀 → 再用插件自己的驱动桥 ``reset()`` 复位一次（幂等）。
    """

    def __init__(self, cfg: IntegratedConfig, plugin_config_path: Path):
        self.cfg = cfg
        self.plugin_config_path = Path(plugin_config_path)
        self.proc: subprocess.Popen | None = None
        self.stop_path = ""
        self.restore_result = ""

    # ------------------------------------------------------------------ #
    def start(self, extra_args: list[str] | None = None) -> None:
        plugin_dir = Path(self.cfg.plugin_dir)
        cmd = [sys.executable, "main.py",
               "--mode", "emg",
               "--policy", "balance",
               "--config", str(self.plugin_config_path)]
        if self.cfg.duration:
            # 让插件自己到点收尾（这条路一定会复位 DPI），留一点余量
            cmd += ["--cap", str(int(self.cfg.duration) + 30)]
        if extra_args:
            cmd += list(extra_args)
        creationflags = 0
        if os.name == "nt":
            creationflags = subprocess.CREATE_NEW_PROCESS_GROUP
        env = dict(os.environ, PYTHONIOENCODING="utf-8")
        self.proc = subprocess.Popen(
            cmd, cwd=str(plugin_dir), env=env, creationflags=creationflags,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
            encoding="utf-8", errors="replace", bufsize=1,
        )

    def wait_ready(self, timeout: float = 20.0) -> bool:
        return wait_for_port(self.cfg.host, self.cfg.port, timeout)

    def drain_output(self, max_lines: int = 40) -> list[str]:
        """读走插件已输出的行（不清空管道会把它写阻塞）。"""
        if self.proc is None or self.proc.stdout is None:
            return []
        lines: list[str] = []
        try:
            os.set_blocking(self.proc.stdout.fileno(), False)
        except (OSError, AttributeError, ValueError):
            return []
        try:
            for _ in range(max_lines):
                line = self.proc.stdout.readline()
                if not line:
                    break
                lines.append(line.rstrip())
        except (OSError, ValueError):
            pass
        return lines

    # ------------------------------------------------------------------ #
    def stop(self) -> str:
        """返回实际走的收尾路径，便于写进汇总。"""
        if self.proc is None:
            return "not_started"
        alive = self.proc.poll() is None
        if alive:
            self._send_graceful()
            try:
                self.proc.wait(timeout=self.cfg.stop_grace_sec)
                self.stop_path = "graceful(plugin restored itself)"
            except subprocess.TimeoutExpired:
                self.proc.terminate()
                try:
                    self.proc.wait(timeout=3.0)
                except subprocess.TimeoutExpired:
                    self.proc.kill()
                    try:
                        self.proc.wait(timeout=3.0)
                    except subprocess.TimeoutExpired:
                        pass
                self.stop_path = "forced(killed; fallback restore)"
        else:
            self.stop_path = f"already_exited(rc={self.proc.returncode})"

        # 兜底：无论上面走哪条路，都用插件自己的驱动桥再复位一次（幂等）
        self.restore_result = self._restore_dpi()
        return self.stop_path

    def _send_graceful(self) -> None:
        assert self.proc is not None
        try:
            if os.name == "nt":
                self.proc.send_signal(signal.CTRL_BREAK_EVENT)
            else:
                self.proc.send_signal(signal.SIGINT)
        except (OSError, ValueError):
            try:
                self.proc.terminate()
            except OSError:
                pass

    def _restore_dpi(self) -> str:
        """借用插件自己的 rawaccel_bridge 复位到 sens=1.0（800 DPI）。"""
        plugin_dir = str(Path(self.cfg.plugin_dir).resolve())
        if plugin_dir not in sys.path:
            sys.path.insert(0, plugin_dir)
        try:
            import rawaccel_bridge  # type: ignore

            data = json.loads(self.plugin_config_path.read_text(encoding="utf-8"))
            bridge = rawaccel_bridge.make_bridge(data.get("rawaccel", {}), quiet=True)
            bridge.reset()
            return ("dry_run(driver not written)" if self.cfg.dry_run
                    else "restored 800 DPI (driver bridge reset)")
        except Exception as exc:  # pragma: no cover - 依赖插件是否存在
            return f"restore not performed: {exc}"
        finally:
            try:
                sys.path.remove(plugin_dir)
            except ValueError:
                pass


class BalanceMonitor:
    """读插件写的 ``balance_events_*.csv``，给统一状态行提供档位/切换次数。"""

    def __init__(self, session_dir: str | Path):
        self.session_dir = Path(session_dir)
        self.path: Path | None = None
        self.rows: list[dict[str, str]] = []
        self._offset = 0
        self._header: list[str] | None = None

    def _find(self) -> Path | None:
        if self.path is not None and self.path.exists():
            return self.path
        found = sorted(glob.glob(str(self.session_dir / "balance_events*.csv")))
        if not found:
            return None
        self.path = Path(found[-1])
        return self.path

    # ------------------------------------------------------------------ #
    def poll(self) -> list[dict[str, str]]:
        """增量读取新行（插件每次写入都会 flush，所以能实时看到）。

        两个必须小心的地方：

        * 插件可能在我第一次轮询**之前**就写好了表头，也可能一个字节都还没写；
          所以表头单独读一次并缓存，**不能**依赖 ``csv.DictReader`` 隐式认表头
          （文件为空时它的 ``fieldnames`` 会停在 None，之后再来新行就崩）。
        * ``reason`` 列里有逗号（``... >=2, confirm=5s``），必须用 ``csv`` 解析，
          不能按逗号 split。同理只处理**完整行**，写到一半的行留到下次。
        """
        path = self._find()
        if path is None:
            return []
        raw = ""
        try:
            with path.open("r", encoding="utf-8", newline="") as fh:
                if self._header is None:
                    first = fh.readline()
                    if not first:
                        return []
                    self._header = [c.strip() for c in first.rstrip("\r\n").split(",")]
                    self._offset = fh.tell()
                fh.seek(self._offset)
                raw = fh.read()
                if not raw:
                    return []
                if raw.endswith("\n"):
                    self._offset += len(raw.encode("utf-8"))
                else:
                    cut = raw.rfind("\n")
                    if cut < 0:
                        return []
                    raw = raw[: cut + 1]
                    self._offset += len(raw.encode("utf-8"))
        except OSError:
            return []

        fresh: list[dict[str, str]] = []
        for row in csv.reader(io.StringIO(raw)):
            if not row or len(row) != len(self._header):
                continue
            fresh.append(dict(zip(self._header, row)))
        self.rows.extend(fresh)
        return fresh

    # ------------------------------------------------------------------ #
    @property
    def switches(self) -> int:
        return sum(1 for r in self.rows if r.get("event") == "SWITCH")

    @property
    def crossings(self) -> int:
        return sum(1 for r in self.rows if r.get("event") == "CROSSING")

    @property
    def level(self) -> str:
        """当前档位：取最后一次动作后的结果（up→high, down→low）。"""
        level = "?"
        for r in self.rows:
            if r.get("event") == "BASELINE_READY":
                level = r.get("level") or level
            elif r.get("event") == "SWITCH":
                level = "high" if r.get("action") == "up" else "low"
        return level

    @property
    def last_reason(self) -> str:
        return self.rows[-1].get("reason", "") if self.rows else ""

    @property
    def mode(self) -> str:
        for r in self.rows:
            if r.get("event") == "BASELINE_READY":
                reason = r.get("reason", "")
                if "mode=" in reason:
                    return reason.split("mode=")[1].split()[0]
        return "?"

    def summary_line(self) -> str:
        return (f"plugin: level={self.level} switches={self.switches} "
                f"crossings={self.crossings} mode={self.mode}")


