def session_dir_for(cfg: IntegratedConfig, when: float | None = None) -> Path:
    stamp = time.strftime("%Y%m%d_%H%M%S", time.localtime(when or time.time()))
    name = f"session_{stamp}"
    if cfg.subject_id:
        safe = "".join(c for c in cfg.subject_id if c.isalnum() or c in "-_")
        if safe:
            name += f"_{safe}"
    root = Path(cfg.out_dir) / name
    suffix = 1
    while root.exists():
        root = Path(cfg.out_dir) / f"{name}_{suffix}"
        suffix += 1
    root.mkdir(parents=True, exist_ok=True)
    return root.resolve()


def run_integrated(
    cfg: IntegratedConfig,
    source_factory,
    printer=print,
) -> dict[str, Any]:
    """跑一次集成会话：起插件 → 采集 → 推 %MVC → 统一状态 → 安全收尾。

    ``source_factory(cfg)`` 由调用方提供（真实 LSL 或合成源），返回 SampleSource。
    """
    from .channels import MultiChannelMvc
    from .config import AppConfig
    from .emg_link import MvcCsvRecorder, MvcTcpSender

    problems = check_contract(cfg)
    if problems:
        for p in problems:
            printer(f"  x {p}")
        raise ValueError(f"Integrated config failed check ({len(problems)} problems)")

    session_dir = session_dir_for(cfg)
    plugin_cfg_path = session_dir / "plugin_config.json"
    plugin_cfg = build_plugin_config(cfg, session_dir)
    plugin_cfg_path.write_text(
        json.dumps(plugin_cfg, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    summary: dict[str, Any] = {
        "started_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "session_dir": str(session_dir),
        "dry_run": cfg.dry_run,
        "channels": cfg.channels,
        "mvc": dict(cfg.mvc),
        "pair": list(cfg.pair),
    }

    printer("=" * 74)
    printer("  Integrated session: signal side (lsl_apdf) + actuator side (DPI plugin)")
    printer("=" * 74)
    printer(f"  Session dir : {session_dir}")
    printer(f"  Plugin cfg  : {plugin_cfg_path.name} (generated by this layer, single source)")
    printer(f"  balance     : pair={cfg.pair} deadband={cfg.deadband} "
            f"confirm={cfg.confirm_sec}s window={cfg.roll_window_sec}s "
            f"baseline={cfg.baseline_sec}s deadtime=ramp{cfg.switch_ramp_sec:g}s+settle{cfg.settle_sec:g}s")
    printer(f"  Driver      : {'DRY-RUN (driver not written)' if cfg.dry_run else '* writing Raw Accel'}")
    printer("=" * 74)

    plugin: PluginProcess | None = None
    sender: MvcTcpSender | None = None
    recorder: MvcCsvRecorder | None = None
    source = None
    monitor = BalanceMonitor(session_dir)
    t_start = time.time()
    try:
        # 1) 执行侧
        if cfg.launch_plugin:
            plugin = PluginProcess(cfg, plugin_cfg_path)
            plugin.start()
            printer(f"  Starting plugin (port {cfg.host}:{cfg.port})...")
            if not plugin.wait_ready(cfg.stop_grace_sec + 12):
                for line in plugin.drain_output():
                    printer(f"    [plugin] {line}")
                raise RuntimeError(
                    f"Plugin did not become ready on port {cfg.port}; the [plugin] lines above are its output"
                )
            printer("  Plugin ready (waiting for %MVC)")
        else:
            if not wait_for_port(cfg.host, cfg.port, timeout=3.0):
                raise RuntimeError(
                    f"Nothing is listening on {cfg.host}:{cfg.port}; "
                    "start the plugin first, or set launch_plugin to true"
                )
            printer("  Connected to the externally running plugin")

        # 2) 信号侧
        source = source_factory(cfg)
        meta = source.connect()
        pipeline = MultiChannelMvc.from_spec(
            fs=meta.nominal_srate,
            channel_spec=cfg.channels,
            mvc_spec=cfg.mvc,
            meta=meta,
            signal_cfg=AppConfig.from_dict({"signal": cfg.signal}).signal
            if cfg.signal else None,
        )
        printer(f"  Source   : {meta.describe()}")
        printer(f"  Channels : {pipeline.describe()}")
        summary["stream"] = {
            "name": meta.name, "type": meta.type,
            "n_channels": meta.n_channels, "nominal_srate": meta.nominal_srate,
        }

        sender = MvcTcpSender(host=cfg.host, port=cfg.port, retry_interval=0.5)
        sender.connect(force=True)
        recorder = MvcCsvRecorder(session_dir / "pctmvc.csv", pipeline.muscles)
        recorder.open()

        # 3) 主循环
        send_interval = 1.0 / max(cfg.send_hz, 0.01)
        next_send = 0.0
        next_report = 0.0
        latest: dict[str, float] = {}
        plugin_lines: list[str] = []
        printer("-" * 74)
        while True:
            chunk = source.read_chunk(timeout=0.05)
            if chunk is not None and len(chunk):
                times, values = pipeline.push(chunk.data, chunk.timestamps)
                if times.size:
                    latest = pipeline.latest(values)
                    if latest:
                        recorder.write(float(times[-1]), latest, t_wall=time.time())
            now = time.time()
            if latest and now >= next_send:
                sender.send(latest)
                next_send = now + send_interval
            for line in monitor.poll():
                if line.get("event") in ("BASELINE_READY", "SWITCH", "CROSSING"):
                    printer(f"    [plugin] {line['t_sim']:>8}s {line['event']:<14} "
                            f"{line.get('action','')!s:<5} {line.get('reason','')}")
            if plugin is not None:
                plugin_lines.extend(plugin.drain_output())
            if now - t_start >= next_report:
                mv = " ".join(f"{k}={v:5.1f}" for k, v in sorted(latest.items())) or "-"
                printer(f"  t={now - t_start:6.1f}s | %MVC {mv} | "
                        f"TCP sent {sender.stats.sent}/failed {sender.stats.failed} | "
                        f"{monitor.summary_line()}")
                next_report = now - t_start + cfg.report_sec
            if cfg.duration is not None and (now - t_start) >= cfg.duration:
                break

    except KeyboardInterrupt:
        printer("\n  Received Ctrl+C; shutting down safely...")
        summary["interrupted"] = True
    finally:
        summary["duration_sec"] = round(time.time() - t_start, 2)
        if recorder is not None:
            recorder.close()
            summary["pctmvc_rows"] = recorder.rows
            summary["pctmvc_csv"] = str(recorder.path)
        if sender is not None:
            summary["tcp"] = sender.stats.as_dict()
            sender.close()
        if source is not None:
            try:
                source.close()
            except Exception:
                pass
        if plugin is not None:
            path = plugin.stop()
            summary["plugin_stop_path"] = path
            summary["dpi_restore"] = plugin.restore_result
            summary["plugin_output_tail"] = plugin_lines[-20:]
        monitor.poll()
        summary["balance"] = {
            "switches": monitor.switches,
            "crossings": monitor.crossings,
            "final_level": monitor.level,
            "mode": monitor.mode,
            "event_log": str(monitor.path) if monitor.path else None,
        }
        summary["finished_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
        (session_dir / "session_summary.json").write_text(
            json.dumps(summary, indent=2, ensure_ascii=False, default=str),
            encoding="utf-8",
        )

    printer("-" * 74)
    printer("  Integrated session finished")
    printer(f"    duration    {summary['duration_sec']} s")
    printer(f"    %MVC log    {summary.get('pctmvc_csv', '-')} ({summary.get('pctmvc_rows', 0)} rows)")
    printer(f"    TCP         {summary.get('tcp')}")
    printer(f"    plugin stop {summary.get('plugin_stop_path')} / {summary.get('dpi_restore')}")
    b = summary["balance"]
    printer(f"    balance     switches {b['switches']} / crossings {b['crossings']} / "
            f"final level {b['final_level']} / mode {b['mode']}")
    printer(f"    summary     {session_dir / 'session_summary.json'}")
    printer("=" * 74)
    return summary
