@dataclass
class IntegratedConfig:
    """一次集成会话的全部参数（**两边共用这一份**）。"""

    plugin_dir: str = r"..\插件\plugin"
    channels: str = "A1=ECU,A2=FDS,A3=UT,A4=EDC"
    mvc: dict[str, float] = field(default_factory=lambda: {
        "ECU": 80.0, "FDS": 57.0, "UT": 83.0, "EDC": 59.0,
    })

    # --- balance 策略（写进插件配置） ---
    pair: list[str] = field(default_factory=lambda: ["ECU", "FDS"])
    direction: dict[str, str] = field(default_factory=lambda: {
        "ECU": "up", "UT": "up", "FDS": "down", "EDC": "down",
    })
    high_thr: float = 20.0
    roll_window_sec: float = 300.0
    baseline_sec: float = 300.0
    deadband: float = 0.15
    deadband_abs_mvc: float = 2.0
    compare: str = "auto"
    """高暴露比较口径：``auto``=基线够大时比相对自己基线的倍数（默认）；
    ``ratio``=只要基线 >0 就比倍数；``absolute``=直接比原始高暴露面积/速率
    （死区改用 deadband_abs_mvc，单位 %MVC）。"""
    compare_interval_sec: float = 0.0
    """定刻比较间隔（秒）：>0 时每隔这么久才比较/判定一次（如 900=每 15 分钟）；
    0 = 连续判定（默认，需 confirm_sec 确认）。"""
    metric: str = "apdf_level"
    """比较量。``apdf_level``（默认，有文献依据）：直接比较两块肌肉的
    **APDF 百分位水平**（Jonsson 1982 的 static/median/peak load level）——
    水平本身已是各自归一化的 %MVC，量纲相同，直接取差即可，不做任何加权合成。
    ``excess_area``：自造的"超阈值强度×时间"积分量，**论文不应使用**，仅为对照保留。"""
    level_percentile: float = 50.0
    """用哪个百分位做比较：50=median load level（默认），10=static，90=peak。"""
    confirm_sec: float = 30.0
    settle_sec: float = 120.0
    safety_mvc: float = 40.0

    # --- 驱动 / 档位 ---
    dry_run: bool = True
    """默认 True（安全）。正式实验才设 false —— 那会真的改鼠标 DPI。"""
    switch_ramp_sec: float = 300.0
    levels: dict[str, dict[str, float]] = field(default_factory=lambda: {
        "low": {"dpi": 800, "sens": 1.0},
        "high": {"dpi": 1200, "sens": 1.5},
    })

    # --- 连接 / 运行 ---
    host: str = "127.0.0.1"
    port: int = 9000
    send_hz: float = 2.0
    duration: float | None = None
    report_sec: float = 10.0
    out_dir: str = "sessions"
    subject_id: str = ""
    launch_plugin: bool = True
    stop_grace_sec: float = 8.0

    # --- 信号侧（透传给本包的采集链） ---
    stream: dict[str, Any] = field(default_factory=dict)
    signal: dict[str, Any] = field(default_factory=dict)

    # ------------------------------------------------------------------ #
    @classmethod
    def load(cls, path: str | Path) -> "IntegratedConfig":
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        known = {f for f in cls.__dataclass_fields__}
        return cls(**{k: v for k, v in data.items()
                      if k in known and not k.startswith("_")})

    def save(self, path: str | Path) -> Path:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        data = {k: v for k, v in self.__dict__.items()}
        path.write_text(json.dumps(data, indent=2, ensure_ascii=False),
                        encoding="utf-8")
        return path

    # ------------------------------------------------------------------ #
    def balance_block(self, event_log: str | None = None) -> dict[str, Any]:
        block: dict[str, Any] = {
            "_comment": "Generated by the lsl_apdf integration layer; shares the signal-side channel mapping. Do not edit by hand.",
            "pair": list(self.pair),
            "direction": dict(self.direction),
            "high_thr": self.high_thr,
            "roll_window_sec": self.roll_window_sec,
            "baseline_sec": self.baseline_sec,
            "floor_mvc": 1.0,
            "deadband": self.deadband,
            "deadband_abs_mvc": self.deadband_abs_mvc,
            "compare": self.compare,
            "compare_interval_sec": self.compare_interval_sec,
            "metric": self.metric,
            "level_percentile": self.level_percentile,
            "confirm_sec": self.confirm_sec,
            "settle_sec": self.settle_sec,
            "safety_mvc": self.safety_mvc,
        }
        if event_log:
            block["event_log"] = event_log
        return block


def build_plugin_config(cfg: IntegratedConfig, session_dir: Path) -> dict[str, Any]:
    """以插件自己的 ``config.json`` 为模板，只覆写本次会话相关的键。

    保留模板里其它字段（模板文件、profile、opensignals 换算等），避免"集成层
    凭空造配置"导致插件行为与它自己的文档不一致。
    """
    plugin_dir = Path(cfg.plugin_dir)
    template_path = plugin_dir / "config.json"
    base: dict[str, Any] = {}
    if template_path.exists():
        base = json.loads(template_path.read_text(encoding="utf-8"))
    else:
        base = {"mouse": {}, "rawaccel": {}, "emg": {}, "log_dir": "logs"}

    session_dir = Path(session_dir).resolve()
    base.setdefault("mouse", {})["levels"] = {
        k: dict(v) for k, v in cfg.levels.items()
    }
    ra = base.setdefault("rawaccel", {})
    ra["dry_run"] = bool(cfg.dry_run)

    emg = base.setdefault("emg", {})
    emg["host"] = cfg.host
    emg["port"] = int(cfg.port)
    emg["protocol"] = "text"
    emg["policy"] = "balance"
    emg["switch_ramp_sec"] = float(cfg.switch_ramp_sec)
    # 日志统一落到会话目录（插件对相对路径会按它自己的目录解析，所以给绝对路径）
    emg["balance"] = cfg.balance_block(
        event_log=str(session_dir / "balance_events.csv")
    )

    base["log_dir"] = str(session_dir)
    base["time_scale"] = 1.0
    base.setdefault("ui", {})["lang"] = "en"
    return base


def check_contract(cfg: IntegratedConfig) -> list[str]:
    """启动前的契约检查：把"静默什么都不做"变成"启动就报错"。"""
    problems: list[str] = []
    mapping = parse_channel_spec(cfg.channels)
    mvc = parse_mvc_spec(cfg.mvc)

    if not mapping:
        problems.append("channels is empty; expected e.g. A1=ECU,A2=FDS,A3=UT,A4=EDC")
    muscles = set(mapping.values())

    if len(cfg.pair) != 2:
        problems.append(f"pair must contain exactly two muscles, got {cfg.pair}")
    for m in cfg.pair:
        if m not in muscles:
            problems.append(
                f"Muscle {m} from pair is not in the channels mapping (mapped: {sorted(muscles)}) "
                "-- the plugin would receive no data for it and silently never switch"
            )
    for m in cfg.pair:
        v = mvc.get(m)
        if v is None:
            problems.append(f"Missing MVC baseline for {m} (pass --mvc, e.g. {m}=80)")
        elif not (v > 0):
            problems.append(f"MVC for {m} must be positive, got {v}")
    for m, d in cfg.direction.items():
        if d not in ("up", "down"):
            problems.append(f"direction[{m}] must be up/down, got {d!r}")
    for m in cfg.pair:
        if m not in cfg.direction:
            problems.append(f"Missing direction mapping for {m}")

    if not (0 < cfg.port < 65536):
        problems.append(f"Invalid port: {cfg.port}")
    if cfg.send_hz <= 0:
        problems.append(f"send_hz must be > 0, got {cfg.send_hz}")
    if cfg.compare not in ("auto", "ratio", "absolute"):
        problems.append(
            f"compare must be auto/ratio/absolute, got {cfg.compare!r}")
    if cfg.metric not in ("apdf_level", "excess_area"):
        problems.append(
            f"metric must be apdf_level/excess_area, got {cfg.metric!r}")
    if not 1.0 <= cfg.level_percentile <= 99.0:
        problems.append(
            f"level_percentile must be within 1..99, got {cfg.level_percentile!r}")
    if cfg.compare_interval_sec < 0:
        problems.append(
            f"compare_interval_sec must not be negative, got {cfg.compare_interval_sec}")

    plugin_dir = Path(cfg.plugin_dir)
    if cfg.launch_plugin:
        if not (plugin_dir / "main.py").exists():
            problems.append(f"main.py not found in plugin_dir: {plugin_dir}")
    if cfg.dry_run is False and not (plugin_dir / "main.py").exists():
        problems.append("Not a dry run but the plugin directory is unavailable; cannot restore DPI")

    if cfg.duration is not None and cfg.duration <= 0:
        problems.append(f"duration must be > 0, got {cfg.duration}")
    return problems


