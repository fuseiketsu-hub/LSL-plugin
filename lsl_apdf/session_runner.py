"""组合集成：把"信号侧"（本包）与"执行侧"（DPI 插件）合成一次会话。

为什么要这一层
--------------
两边的联调接口是 TCP，能跑；但**手动开两个终端**有两个真实风险：

1. **静默错配**：本包按 ``--channels`` 发 ``ECU/FDS``，插件按自己的 ``config.json``
   监听某个肌肉对。只要名字或肌肉对不一致，插件就收不到需要的数据、**一声不响地
   什么都不做**（既没报错也没切换），现场很难发现。
2. **停止时没复位**：插件靠 ``finally: ctrl.stop(restore=True)`` 复位 800 DPI，
   而在 Windows 上强杀进程**不会**执行它 —— 鼠标灵敏度会停在 1200。

所以本模块做三件事：

* **一份配置管两边**：从同一次会话配置生成插件的配置文件（端口、balance 参数、
  日志路径），并**先做契约检查**（肌肉对 ⊆ 发送的通道、每块肌肉都有 MVC）；
* **统一状态行**：把"流 / %MVC / TCP 发送 / 插件当前档位 / 切换次数"打在一行里，
  操作者不用盯两个窗口；
* **安全收尾**：先尝试优雅停止（让插件自己复位），再兜底用插件自己的驱动桥
  ``reset()`` 复位一次（幂等），最后才强杀。

产物全部落在**同一个会话目录**：``pctmvc.csv``（含 LSL 与墙钟双时间戳）、
``plugin_config.json``（本次实际用的插件配置，保证可复现）、
``session_summary.json``，以及插件写的 ``sens_log_*.csv`` / ``balance_events_*.csv``。
"""

